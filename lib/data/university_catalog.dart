    try {
      return allCourses.firstWhere((c) => c.id == id);
    } catch (_) {
      return null;
    }
  }

  static Course? getCourseByCode(String code) {
    try {
      return allCourses.firstWhere((c) => c.code.toUpperCase() == code.toUpperCase());
    } catch (_) {
      return null;
    }
  }
